(function(){
  var SUPPORTED = ["ko","ru","zh","mn","en"];

  function applyLang(lang){
    var dict = I18N[lang] || I18N.ko;
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(function(el){
      var v = dict[el.dataset.i18n];
      if(v !== undefined) el.textContent = v;
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function(el){
      var v = dict[el.dataset.i18nHtml];
      if(v !== undefined) el.innerHTML = v;
    });
    document.querySelectorAll("[data-i18n-attr]").forEach(function(el){
      var parts = el.dataset.i18nAttr.split("|");
      var v = dict[parts[1]];
      if(v !== undefined) el.setAttribute(parts[0], v);
    });
    document.querySelectorAll(".langs button").forEach(function(b){
      b.setAttribute("aria-current", String(b.dataset.lang === lang));
    });
    try{ localStorage.setItem("mj-lang", lang); }catch(e){}
  }

  function detect(){
    var saved;
    try{ saved = localStorage.getItem("mj-lang"); }catch(e){}
    if(saved && SUPPORTED.indexOf(saved) > -1) return saved;

    var navs = (navigator.languages && navigator.languages.length)
      ? navigator.languages : [navigator.language || "ko"];
    for(var i=0; i<navs.length; i++){
      var t = String(navs[i]).toLowerCase();
      if(t.indexOf("mn") === 0) return "mn";
      if(t.indexOf("ru") === 0 || t.indexOf("uk") === 0 || t.indexOf("kk") === 0 ||
         t.indexOf("uz") === 0 || t.indexOf("ky") === 0 || t.indexOf("tg") === 0) return "ru";
      if(t.indexOf("zh") === 0) return "zh";
      if(t.indexOf("ko") === 0) return "ko";
      if(t.indexOf("en") === 0) return "en";
    }
    return "ko";
  }

  document.querySelectorAll(".langs button").forEach(function(b){
    b.addEventListener("click", function(){ applyLang(b.dataset.lang); });
  });

  applyLang(detect());
})();
